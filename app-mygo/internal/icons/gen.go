//go:build ignore

// gen writes icons_gen.go and MaterialIcons-Subset.otf: the Material icons the
// Flutter client uses (every Icons.name under ../app/lib), at the codepoints
// Flutter's icons.dart gives them, and the glyphs of Flutter's own
// MaterialIcons font for those codepoints alone. Run it with go generate
// after the Flutter client starts using another icon; it needs Flutter
// (FLUTTER_ROOT, or /opt/flutter) and fontTools' pyftsubset.
package main

import (
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

func main() {
	flutter := os.Getenv("FLUTTER_ROOT")
	if flutter == "" {
		flutter = "/opt/flutter"
	}
	used := map[string]bool{}
	ref := regexp.MustCompile(`Icons\.([a-z0-9_]+)`)
	err := filepath.WalkDir("../../../app/lib", func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".dart") {
			return err
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for _, m := range ref.FindAllStringSubmatch(string(src), -1) {
			used[m[1]] = true
		}
		return nil
	})
	if err != nil {
		log.Fatal(err)
	}
	// Flutter's own widgets draw these: the back and close buttons, the
	// expansion tile's and the drop-down's arrows, the chip's delete icon,
	// the segmented button's check, submenu arrows, and the pickers' icons.
	for _, n := range []string{"arrow_back", "close", "expand_more", "arrow_drop_down", "arrow_drop_up",
		"cancel", "check", "more_vert", "arrow_right", "search", "clear", "keyboard_arrow_left",
		"keyboard_arrow_right", "chevron_left", "chevron_right", "edit", "calendar_today", "keyboard", "access_time"} {
		used[n] = true
	}
	dart, err := os.ReadFile(filepath.Join(flutter, "packages/flutter/lib/src/material/icons.dart"))
	if err != nil {
		log.Fatal(err)
	}
	decl := regexp.MustCompile(`static const IconData ([a-z0-9_]+) = IconData\(\s*0x([0-9a-f]+),\s*fontFamily: 'MaterialIcons'(,\s*matchTextDirection: true)?`)
	points := map[string]string{}
	mirrored := map[string]bool{}
	for _, m := range decl.FindAllStringSubmatch(string(dart), -1) {
		points[m[1]] = m[2]
		mirrored[m[1]] = m[3] != ""
	}
	names := make([]string, 0, len(used))
	for n := range used {
		if _, ok := points[n]; !ok {
			log.Fatalf("Icons.%s is not in icons.dart", n)
		}
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// Code generated by gen.go from Flutter's icons.dart; DO NOT EDIT.\n\npackage icons\n\nconst (\n")
	var unicodes []string
	for _, n := range names {
		fmt.Fprintf(&b, "\t%s Icon = 0x%s\n", goName(n), points[n])
		unicodes = append(unicodes, "U+"+points[n])
	}
	b.WriteString(")\n\n// mirrored are the icons Flutter flips in right-to-left text.\nvar mirrored = map[Icon]bool{\n")
	for _, n := range names {
		if mirrored[n] {
			fmt.Fprintf(&b, "\t%s: true,\n", goName(n))
		}
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("icons_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fonts := filepath.Join(flutter, "bin/cache/artifacts/material_fonts")
	cmd := exec.Command("pyftsubset", filepath.Join(fonts, "MaterialIcons-Regular.otf"),
		"--unicodes="+strings.Join(unicodes, ","), "--output-file=MaterialIcons-Subset.otf",
		"--no-hinting", "--layout-features=")
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		log.Fatal(err)
	}
	license, err := os.ReadFile(filepath.Join(fonts, "MaterialIcons_LICENSE.txt"))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("MaterialIcons_LICENSE.txt", license, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d icons\n", len(names))
}

// goName turns add_circle_outline_rounded into AddCircleOutlineRounded.
func goName(n string) string {
	var b strings.Builder
	for _, part := range strings.Split(n, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	s := b.String()
	if s[0] >= '0' && s[0] <= '9' {
		s = "N" + s
	}
	return s
}
